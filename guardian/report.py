#!/usr/bin/env python3
"""
Incident Report Generator
=========================
logs/alerts.csv + logs/telemetry.csv pore ekta standalone HTML
incident report banay (kono external library lage na).

Cholao:  python -m guardian.report  ->  logs/report.html
"""
import csv
import html
from collections import Counter
from pathlib import Path

LOG_DIR = Path(__file__).parent.parent / "logs"
SEV_COLOR = {"CRITICAL": "#c0392b", "WARNING": "#b7791f", "INFO": "#2b6cb0"}


def _read(path):
    if not Path(path).exists():
        return []
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def build(log_dir=LOG_DIR):
    alerts = _read(Path(log_dir) / "alerts.csv")
    telem = _read(Path(log_dir) / "telemetry.csv")
    counts = Counter(a["severity"] for a in alerts)
    total = len(alerts)

    # severity count bars (inline svg, accessible colors)
    bars = ""
    maxc = max(counts.values()) if counts else 1
    for sev in ["CRITICAL", "WARNING", "INFO"]:
        c = counts.get(sev, 0)
        w = int(c / maxc * 260) if maxc else 0
        bars += (f'<div class="barrow"><span class="sev" style="color:{SEV_COLOR[sev]}">{sev}</span>'
                 f'<span class="bar" style="width:{w}px;background:{SEV_COLOR[sev]}"></span>'
                 f'<span class="cnt">{c}</span></div>')

    rows = ""
    for a in reversed(alerts[-200:]):
        col = SEV_COLOR.get(a["severity"], "#555")
        rows += (f'<tr><td class="ts">{html.escape(a["timestamp"])}</td>'
                 f'<td><span class="pill" style="background:{col}">{html.escape(a["severity"])}</span></td>'
                 f'<td class="rid">{html.escape(a["rule_id"])}</td>'
                 f'<td>{html.escape(str(a["value"]))}</td>'
                 f'<td>{html.escape(a["message"])}</td></tr>')
    if not rows:
        rows = '<tr><td colspan="5" class="empty">No alerts logged yet. Run the monitor with --log.</td></tr>'

    verdict = "CRITICAL incident(s) detected" if counts.get("CRITICAL") else (
        "Warnings only" if total else "No anomalies")

    doc = f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Reactor ICS Incident Report</title>
<style>
:root{{--bg:#f7f8fa;--card:#fff;--fg:#1a202c;--muted:#64748b;--line:#e2e8f0}}
@media (prefers-color-scheme:dark){{:root:not([data-theme=light]){{--bg:#0f1420;--card:#1a2130;--fg:#e8edf4;--muted:#94a3b8;--line:#2a3550}}}}
*{{box-sizing:border-box}}
body{{margin:0;background:var(--bg);color:var(--fg);font:15px/1.5 -apple-system,Segoe UI,Roboto,sans-serif;padding:24px 16px}}
.wrap{{max-width:900px;margin:0 auto}}
h1{{font-size:22px;margin:0 0 4px}}
.sub{{color:var(--muted);margin:0 0 20px}}
.cards{{display:flex;gap:12px;flex-wrap:wrap;margin-bottom:20px}}
.card{{background:var(--card);border:1px solid var(--line);border-radius:12px;padding:16px;flex:1;min-width:150px}}
.big{{font-size:28px;font-weight:700}}
.barrow{{display:flex;align-items:center;gap:10px;margin:6px 0}}
.sev{{width:78px;font-weight:600;font-size:13px}}
.bar{{height:14px;border-radius:7px;min-width:3px}}
.cnt{{color:var(--muted)}}
table{{width:100%;border-collapse:collapse;background:var(--card);border:1px solid var(--line);border-radius:12px;overflow:hidden}}
th,td{{text-align:left;padding:10px 12px;border-bottom:1px solid var(--line);font-size:13px;vertical-align:top}}
th{{color:var(--muted);font-weight:600;text-transform:uppercase;font-size:11px;letter-spacing:.04em}}
.ts{{white-space:nowrap;color:var(--muted);font-variant-numeric:tabular-nums}}
.rid{{font-family:ui-monospace,Menlo,monospace}}
.pill{{color:#fff;padding:2px 8px;border-radius:20px;font-size:11px;font-weight:600}}
.empty{{text-align:center;color:var(--muted);padding:28px}}
footer{{color:var(--muted);font-size:12px;margin-top:18px}}
</style></head><body><div class="wrap">
<h1>☢ Reactor ICS Incident Report</h1>
<p class="sub">Generated by Reactor ICS Guardian · verdict: <b>{verdict}</b></p>
<div class="cards">
  <div class="card"><div class="muted">Total alerts</div><div class="big">{total}</div></div>
  <div class="card"><div class="muted">Critical</div><div class="big" style="color:{SEV_COLOR['CRITICAL']}">{counts.get('CRITICAL',0)}</div></div>
  <div class="card"><div class="muted">Telemetry samples</div><div class="big">{len(telem)}</div></div>
</div>
<div class="card" style="margin-bottom:20px"><b>Alerts by severity</b><div style="margin-top:10px">{bars}</div></div>
<table><thead><tr><th>Time</th><th>Severity</th><th>Rule</th><th>Value</th><th>Detail</th></tr></thead>
<tbody>{rows}</tbody></table>
<footer>Simulation only — no real hardware. reactor-ics-ids.</footer>
</div></body></html>"""
    out = Path(log_dir) / "report.html"
    out.write_text(doc)
    return out, total, counts


if __name__ == "__main__":
    out, total, counts = build()
    print(f"[report] {out}  ({total} alerts: {dict(counts)})")
